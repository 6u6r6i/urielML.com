// Point the period after "A brief bio" at one of the poems above, chosen fresh on
// every load. The anchor ships with a real poem already in its href, so with JS off
// (or if this file fails to load) the link still works — it just stops rotating.
(function () {
    var dot = document.getElementById("poem-dot");
    if (!dot || !window.PARRA_POEMS || !window.PARRA_POEMS.length) return;

    var poem = window.PARRA_POEMS[Math.floor(Math.random() * window.PARRA_POEMS.length)];
    var book = window.PARRA_BOOKS[poem[0].split("/")[0]];

    dot.href = window.PARRA_BASE + poem[0];
    // Many Cristo de Elqui pieces are titled only "LV", "XLII" and so on, so the
    // collection does the explaining in the tooltip.
    dot.title = "“" + poem[1] + "” — Nicanor Parra"
              + (book ? ", " + book : "");
})();
